# Seeing the World: Think of at least five places in the world
#                   you'd like to visit. Store them in a list and
#                   use sort, sorted, reverse, reversed on them.

print("Try-it-Yourself:")
print("Assignment 3.8")

places = ["cairo", "tokyo", "antarctica", "beijing", "australia"]
print(places)

print("---")
print(sorted(places))
print(places)

print("---")
print(sorted(places, reverse=True))
print(places)

print("---")
places.reverse()
print(places)

print("---")
places.reverse()
print(places)

print("---")
places.sort()
print(places)

print("---")
places.sort(reverse=True)
print(places)
